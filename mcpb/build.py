"""Build the Claude Desktop extension (.mcpb) for aivy-mcp.

The bundle holds no code of its own: a manifest, an icon, a pyproject.toml
that depends on the released aivy-mcp from PyPI, and a two-line entry point.
Claude Desktop installs the dependencies with its bundled uv (server type
"uv", manifest 0.4), so the person needs neither Python nor uv.

    uv run --no-project --with .. python mcpb/build.py      # from sdk/aivy-mcp

Writes mcpb/manifest.json and mcpb/pyproject.toml from the package itself
(version, tool list), then packs dist/aivy-mcp-<version>.mcpb with the
official packer (npx @anthropic-ai/mcpb), which also validates the manifest.
"""

from __future__ import annotations

import asyncio
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
WEB = "https://bridge.ivyenergy.com.au"


def main() -> int:
    sys.path.insert(0, str(ROOT / "src"))
    from aivy_mcp import __version__
    import aivy_mcp.server as server

    tools = asyncio.run(server.mcp.list_tools())
    manifest = {
        "$schema": "https://raw.githubusercontent.com/anthropics/mcpb/main/dist/mcpb-manifest.schema.json",
        "manifest_version": "0.4",
        "name": "aivy-mcp",
        "display_name": "Aivy Energy",
        "version": __version__,
        "description": "Read and control your own solar + battery system: Sungrow, Sigenergy, FoxESS, AlphaESS, SolaX.",
        "long_description": (
            "Ask Claude what your battery is doing, what Amber Electric prices look like, when to sell tonight, "
            "and let it set the energy mode or an alert. Sign up or sign in from the chat; the key stays on this "
            "computer. Works with every brand Aivy runs. Manual (forced) modes set here are time-boxed and hand "
            "back automatically; the engine's SOC floor and export limits cannot be overridden."
        ),
        "author": {"name": "Ivy Energy", "email": "info@ivyenergy.com.au", "url": "https://www.ivyenergy.com.au/"},
        "homepage": f"{WEB}/developers",
        "documentation": f"{WEB}/v1/docs",
        "support": "https://github.com/IVYEnergy/aivy-mcp/issues",
        "repository": {"type": "git", "url": "https://github.com/IVYEnergy/aivy-mcp"},
        "icon": "icon.png",
        "server": {
            "type": "uv",
            "entry_point": "src/server.py",
            "mcp_config": {
                "command": "uv",
                "args": ["run", "--directory", "${__dirname}", "src/server.py"],
                "env": {"AIVY_API_KEY": "${user_config.api_key}"},
            },
        },
        "user_config": {
            "api_key": {
                "type": "string",
                "title": "Aivy API key (optional)",
                "description": "Leave empty to sign up or sign in from the chat. Or paste a key from "
                               f"{WEB}/developer (read only, or read and control).",
                "sensitive": True,
                "required": False,
            }
        },
        "tools": [{"name": t.name, "description": (t.description or "").split("\n")[0][:200]} for t in tools],
        "tools_generated": False,
        "keywords": ["solar", "battery", "energy", "amber", "sungrow", "sigenergy", "home-energy", "australia"],
        "license": "Apache-2.0",
        "privacy_policies": [f"{WEB}/privacy"],
        "compatibility": {
            "claude_desktop": ">=0.10.0",
            "platforms": ["darwin", "win32", "linux"],
            "runtimes": {"python": ">=3.10"},
        },
    }
    (HERE / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (HERE / "pyproject.toml").write_text(
        "# Generated by build.py: the extension runs the released package.\n"
        "[project]\n"
        'name = "aivy-mcp-desktop"\n'
        f'version = "{__version__}"\n'
        'description = "Claude Desktop extension for aivy-mcp"\n'
        'requires-python = ">=3.10"\n'
        f'dependencies = ["aivy-mcp=={__version__}"]\n',
        encoding="utf-8",
    )
    out = ROOT / "dist"
    out.mkdir(exist_ok=True)
    target = out / f"aivy-mcp-{__version__}.mcpb"
    subprocess.run(["npx", "--yes", "@anthropic-ai/mcpb", "pack", str(HERE), str(target)], check=True)
    print(f"packed {target} ({target.stat().st_size // 1024} KB, {len(tools)} tools)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
